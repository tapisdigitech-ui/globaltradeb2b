#!/usr/bin/env python3
"""Generates migrations_draft/down/0006_down.sql by diffing two LOCAL clones: g_pre (replica + 0001-0005) and g_post (+0006).
Usage: PGHOST=/tmp/pgt PGPORT=5544 PGUSER=postgres python3 tests/gen_down_0006.py"""
import subprocess, os
def q(db, sql):
    return subprocess.check_output(['psql','-d',db,'-Atc',sql]).decode().strip()
def rows(db, sql, sep='\x1f'):
    out=subprocess.check_output(['psql','-d',db,'-AtF',sep,'-c',sql]).decode()
    return [r.split(sep) for r in out.split('\x1e\n') if r.strip()] if False else [l.split(sep) for l in out.split('\n') if l]
POL="""select c.relnamespace::regnamespace||'.'||c.relname, p.polname,
 'create policy '||p.polname||' on '||c.relnamespace::regnamespace||'.'||c.relname||' for '||case p.polcmd when 'r' then 'select' when 'a' then 'insert' when 'w' then 'update' when 'd' then 'delete' else 'all' end
 ||coalesce(' to '||(select string_agg(rolname,',') from pg_roles where oid=any(p.polroles) and p.polroles<>'{0}'),'')
 ||coalesce(' using ('||pg_get_expr(p.polqual,p.polrelid)||')','')||coalesce(' with check ('||pg_get_expr(p.polwithcheck,p.polrelid)||')','')||';'
 from pg_policy p join pg_class c on c.oid=p.polrelid where c.relnamespace in ('public'::regnamespace,'storage'::regnamespace) order by 1,2"""
pre={ (r[0],r[1]):r[2] for r in rows('g_pre',POL)}
post={(r[0],r[1]):r[2] for r in rows('g_post',POL)}
pre_tables=set(q('g_pre',"select relname from pg_class where relnamespace='public'::regnamespace and relkind='r'").split('\n'))
post_tables=set(q('g_post',"select relname from pg_class where relnamespace='public'::regnamespace and relkind='r'").split('\n'))
new_tables=sorted(post_tables-pre_tables)
FN="""select p.proname||'('||pg_get_function_identity_arguments(p.oid)||')', pg_get_functiondef(p.oid) from pg_proc p where p.pronamespace='public'::regnamespace and p.prokind='f'"""
def fns(db):
    out=subprocess.check_output(['psql','-d',db,'-AtF','\x1f','-R','\x1e','-c',FN]).decode()
    d={}
    for rec in out.split('\x1e'):
        if '\x1f' in rec:
            k,v=rec.split('\x1f',1); d[k.strip()]=v.strip()
    return d
fpre,fpost=fns('g_pre'),fns('g_post')
out=["-- DOWN for 0006_real_schema_hardening. DRAFT, not applied to any Supabase project.",
"-- GENERATED by tests/gen_down_0006.py from a diff of two LOCAL clones (replica+0001-0005 vs +0006): restores the exact post-0005 state.",
"-- Data notes: lead_cases in queue product_enquiry_review are re-queued (not deleted); audit/grant tables created by 0006 are dropped with their rows; product_images.representation is dropped.",
"begin;","-- 1. policies: drop those created by 0006 on pre-existing tables, restore changed originals"]
for k,v in sorted(post.items()):
    tbl=k[0].split('.')[1]
    if k not in pre and tbl in pre_tables: out.append(f"drop policy {k[1]} on {k[0]};")
    elif k in pre and pre[k]!=v: out.append(f"drop policy {k[1]} on {k[0]};"); out.append(pre[k])
for k,v in sorted(pre.items()):
    if k not in post: out.append(v)
out.append("-- 2. FORCE RLS flags")
fl="select relname from pg_class where relnamespace='public'::regnamespace and relkind='r' and relforcerowsecurity"
fpre_f=set(q('g_pre',fl).split('\n')); fpost_f=set(q('g_post',fl).split('\n'))
out+=[f"alter table public.{t} no force row level security;" for t in sorted((fpost_f-fpre_f)&pre_tables)]
out+=["-- 3. lead_cases queue constraint","update public.lead_cases set queue='unverified_matches' where queue='product_enquiry_review';",
"alter table public.lead_cases drop constraint lead_cases_queue_check;",
"alter table public.lead_cases add constraint lead_cases_queue_check check (queue in ('unclaimed_matches','unverified_matches','capped_eligible','unmatched'));",
"-- 4. functions created by 0006 (dropped before the tables they use)"]
for k in sorted(set(fpost)-set(fpre)): out.append(f"drop function public.{k};")
out.append("-- 5. tables created by 0006")
out+=[f"drop table public.{t};" for t in new_tables]
out.append("-- 6. columns added by 0006")
COL="select table_name||'.'||column_name from information_schema.columns where table_schema='public'"
cpre=set(q('g_pre',COL).split('\n')); cpost=set(q('g_post',COL).split('\n'))
for c in sorted(cpost-cpre):
    t,col=c.split('.')
    if t in pre_tables: out.append(f"alter table public.{t} drop column {col};")
out.append("-- 7. replaced or removed functions (restore post-0005 bodies)")
for k in sorted(fpre):
    if k not in fpost or fpost[k]!=fpre[k]: out.append(fpre[k]+";")
    if k not in fpost:   # a re-created function loses its ACL: restore it exactly from the pre clone
        nm=k.split('(')[0]; args=k[k.index('(')+1:-1]
        sig=q('g_pre',f"select p.oid::regprocedure from pg_proc p where p.pronamespace='public'::regnamespace and p.proname='{nm}' and pg_get_function_identity_arguments(p.oid)='{args}'")
        out.append(f"revoke all on function {sig} from public, anon, authenticated, service_role;")
        for g in q('g_pre',f"select case when a.grantee=0 then 'public' else pg_get_userbyid(a.grantee) end from pg_proc p, aclexplode(coalesce(p.proacl, acldefault('f',p.proowner))) a where p.oid='{sig}'::regprocedure and a.privilege_type='EXECUTE' and pg_get_userbyid(a.grantee)<>'postgres'").split('\n'):
            if g: out.append(f"grant execute on function {sig} to {g};")
out.append("commit;")
open('migrations_draft/down/0006_down.sql','w').write("\n".join(out)+"\n")
print("policies restored:",sum(1 for k in post if k in pre and pre[k]!=post[k]),"| functions restored:",sum(1 for k in fpre if k not in fpost or fpost[k]!=fpre[k]),"| new functions dropped:",len(set(fpost)-set(fpre)),"| tables dropped:",len(new_tables))
